# Generates docs/gen/lua-index.md: file -> functions / top-level tables for ref/lua (skips WIP, Mods, modconf, Libs/third-party noise).
# Lua was NOT changed by the legacy mod: consult only when a patched C# method calls into Lua.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$lua = Join-Path $root 'ref\lua'
$skip = @('WIP', 'Mods', 'modconf')
$fnRe = New-Object Text.RegularExpressions.Regex '^\s*(?:local\s+)?function\s+([A-Za-z_][\w\.:]*)\s*\(', 'Compiled'
$fn2Re = New-Object Text.RegularExpressions.Regex '^\s*([A-Za-z_][\w\.]*)\s*=\s*function\s*\(', 'Compiled'
$tblRe = New-Object Text.RegularExpressions.Regex '^(?:local\s+)?([A-Za-z_]\w*)\s*=\s*\{', 'Compiled'
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('# Lua index (generated by scripts/gen-lua-index.ps1). Grep only.')
[void]$sb.AppendLine('Format: path under ref/lua | lines | functions | top-level tables. Skipped dirs: ' + ($skip -join ', '))
[void]$sb.AppendLine('')
$n = 0
foreach ($f in (Get-ChildItem $lua -Recurse -File -Filter *.lua | Sort-Object FullName)) {
    $rel = $f.FullName.Substring($lua.Length).TrimStart('\')
    if ($skip -contains $rel.Split('\')[0]) { continue }
    $fns = New-Object Collections.Generic.List[string]; $tb = New-Object Collections.Generic.List[string]
    $lines = [IO.File]::ReadAllLines($f.FullName)
    foreach ($l in $lines) {
        $m = $fnRe.Match($l); if ($m.Success) { if ($fns.Count -lt 80) { $fns.Add($m.Groups[1].Value) }; continue }
        $m = $fn2Re.Match($l); if ($m.Success) { if ($fns.Count -lt 80) { $fns.Add($m.Groups[1].Value) }; continue }
        $m = $tblRe.Match($l); if ($m.Success -and $tb.Count -lt 30) { $tb.Add($m.Groups[1].Value) }
    }
    [void]$sb.AppendLine("$($rel.Replace('\','/')) | $($lines.Length) | $($fns -join ', ') | $($tb -join ', ')")
    $n++
}
[IO.File]::WriteAllText((Join-Path $root 'docs\gen\lua-index.md'), $sb.ToString())
Write-Host "lua files=$n size=$([int]((Get-Item (Join-Path $root 'docs\gen\lua-index.md')).Length / 1024))KB"
