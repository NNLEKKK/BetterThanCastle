# Generates docs/gen/game-api-index.md: one line per vanilla type -> namespace | path | base | public/protected member signatures.
# Never read this file whole: Grep it for a type or member name.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$van = Join-Path $root 'ref\vanilla'
$skipDirs = @('AmplifyOcclusion', 'I2', 'LibNoise', 'Rewired', 'Steamworks', 'UnityTest', 'ThirdParty', 'Properties', 'RakNet')
$typeRe = New-Object Text.RegularExpressions.Regex '^(\t*)(?:\[[^\]]*\]\s*)*((?:(?:public|internal|private|protected|static|sealed|abstract|partial|unsafe|new)\s+)*)(class|struct|enum|interface)\s+([A-Za-z_]\w*[^\r\n]*)$', 'Compiled'
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('# Vanilla Assembly-CSharp-firstpass API index (generated by scripts/gen-api-index.ps1). Grep only; do not read whole.')
[void]$sb.AppendLine('Format: Type | namespace | path under ref/vanilla | base/interfaces | members (public/protected, "prot" = protected; nested types skipped). Third-party dirs and Ak* (Wwise) are summarised at the end.')
[void]$sb.AppendLine('')
$skipped = @{}
$types = 0
foreach ($f in (Get-ChildItem $van -Recurse -File -Filter *.cs | Sort-Object FullName)) {
    $rel = $f.FullName.Substring($van.Length).TrimStart('\')
    $top = $rel.Split('\')[0]
    if ($skipDirs -contains $top) { $skipped[$top] = 1 + [int]$skipped[$top]; continue }
    if ($rel -notmatch '\\' -and $f.Name -match '^Ak[A-Z]') { $skipped['Ak*'] = 1 + [int]$skipped['Ak*']; continue }
    $lines = [IO.File]::ReadAllLines($f.FullName)
    $ns = ''
    for ($i = 0; $i -lt $lines.Length; $i++) {
        $l = $lines[$i]
        if ($l -match '^namespace\s+([\w\.]+)') { $ns = $Matches[1]; continue }
        $m = $typeRe.Match($l)
        if (-not $m.Success) { continue }
        $d = $m.Groups[1].Length
        if (($ns -ne '' -and $d -ne 1) -or ($ns -eq '' -and $d -ne 0)) { continue }   # top-level types only
        $kind = $m.Groups[3].Value
        $rest = $m.Groups[4].Value
        $name = ($rest -split '[\s:<]')[0]
        $base = ''
        if ($rest -match ':\s*(.+?)\s*(where .*)?$') { $base = $Matches[1] }
        # members: indent d+1
        $mem = New-Object Collections.Generic.List[string]
        $pre = "`t" * ($d + 1)
        $end = "`t" * $d + '}'
        for ($j = $i + 1; $j -lt $lines.Length; $j++) {
            $x = $lines[$j]
            if ($x -eq $end) { break }
            if ($x.StartsWith($pre) -and -not $x.StartsWith($pre + "`t") -and -not $x.StartsWith($pre + '//')) {
                $t = $x.Substring($pre.Length)
                if ($t -match '^(?:\[[^\]]*\]\s*)*(public|protected)\b') {
                    $t = $t -replace '^(?:\[[^\]]*\]\s*)+', ''
                    $t = $t -replace '\s*=>.*$', '' -replace '\s*=\s*[^;(]*;?$', '' -replace '\s*\{.*$', '' -replace ';$', ''
                    $t = $t -replace '^public ', '' -replace '^protected ', 'prot '
                    $t = ($t -replace '\s+', ' ').Trim()
                    if ($t -and -not ($t -match '^(prot )?(class|struct|enum|interface)\b')) { $mem.Add($t) }
                }
            }
        }
        $display = if ($kind -ne 'class') { "$kind $name" } else { $name }
        [void]$sb.AppendLine("$display | $ns | $($rel.Replace('\','/')) | $base | $($mem -join ' ; ')")
        $types++
        break  # one top-level type per decompiled file is the norm; extras are rare
    }
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('## Skipped (third-party / engine bindings): ' + (($skipped.Keys | Sort-Object | ForEach-Object { "$_=$($skipped[$_])" }) -join ', '))
[IO.File]::WriteAllText((Join-Path $root 'docs\gen\game-api-index.md'), $sb.ToString())
Write-Host "types=$types size=$([int]((Get-Item (Join-Path $root 'docs\gen\game-api-index.md')).Length / 1024))KB"
