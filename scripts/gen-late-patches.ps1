param([Parameter(Mandatory=$true)][string]$Dir, [string[]]$KeepEarly = @())
# Writes src/BetterThanCastle/BtcPatchLate.cs: every patch class (patch-classes.txt from a DEV run) that is in none of the
# early-*.txt snapshots in -Dir (BtcDevProbe.SnapshotEarly: classes with a target called before the first world load).
# Labs: tests/scenarios/early-mp (-Clients 1), early-sp, early-replay; copy BTClogs[/host|/client1]/early-*.txt into -Dir.
$root = Split-Path -Parent $PSScriptRoot
$all = [IO.File]::ReadAllLines((Join-Path $Dir 'patch-classes.txt')) | ForEach-Object { $_.Trim() } | Where-Object { $_ }
$early = @{}
foreach ($f in Get-ChildItem $Dir -Filter '*.txt' | Where-Object { $_.Name -ne 'patch-classes.txt' }) {
    foreach ($l in [IO.File]::ReadAllLines($f.FullName)) { $n = $l.Trim(); if ($n) { $early[$n] = 1 } }
}
foreach ($k in $KeepEarly) { $early[$k] = 1 }
# DEV-only patch classes stay out (Release must not carry their names; verify-dist rejects BtcDev strings)
$dev = @{}
foreach ($f in Get-ChildItem (Join-Path $root 'src\BetterThanCastle\Dev') -Filter '*.cs') {
    foreach ($m in [regex]::Matches([IO.File]::ReadAllText($f.FullName), 'class\s+(\w+)')) { $dev[$m.Groups[1].Value] = 1 }
}
$late = $all | Where-Object { -not $early.ContainsKey($_) -and -not $dev.ContainsKey($_) -and $_ -notlike 'BtcDev*' } | Sort-Object -Unique
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('namespace BetterThanCastle')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>GENERATED by scripts/gen-late-patches.ps1 from DEV early-*.txt snapshots (BtcDevProbe.SnapshotEarly):')
[void]$sb.AppendLine('    /// patch classes whose targets were never called before the first world load (menu, lobby host/client, replay).')
[void]$sb.AppendLine('    /// BtcPatcher applies them on a background thread. A class missing here is applied on the main thread (safe default).</summary>')
[void]$sb.AppendLine('    internal static class BtcPatchLate')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        internal static readonly string[] Classes =')
[void]$sb.AppendLine('        {')
foreach ($n in $late) { [void]$sb.AppendLine('            "' + $n + '",') }
[void]$sb.AppendLine('        };')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText((Join-Path $root 'src\BetterThanCastle\BtcPatchLate.cs'), $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
"all=$($all.Count) early=$($early.Count) late=$(@($late).Count)"
