        [STAThread]
        private static int Main(string[] args)
        {
            // Silent mode for scripts/tests: BetterThanCastle-Setup.exe /silent "<game dir>" [/ignore-running]
            // (winexe has no console: the log goes to %TEMP%\BetterThanCastle-Setup.log).
            if (args.Length >= 2 && args[0].Equals("/silent", StringComparison.OrdinalIgnoreCase))
            {
                Installer.IgnoreRunning = args.Length >= 3 && args[2].Equals("/ignore-running", StringComparison.OrdinalIgnoreCase);
                string logPath = Path.Combine(Path.GetTempPath(), "BetterThanCastle-Setup.log");
                var lines = new List<string>();
                int code = 0;
                try { lines.Add(Installer.Install(args[1], delegate(string s) { lines.Add(s); })); }
                catch (Exception e) { lines.Add("ERROR: " + e.Message); code = 1; }
                try { File.WriteAllLines(logPath, lines.ToArray()); } catch { }
                return code;
            }
            // Discovery test: BetterThanCastle-Setup.exe /list -> %TEMP%\BetterThanCastle-Setup.log (fast sources, then disk scan).
            if (args.Length >= 1 && args[0].Equals("/list", StringComparison.OrdinalIgnoreCase))
            {
                var f = new Installer.Found();
                var sw = Stopwatch.StartNew();
                Installer.FindFast(f);
                var lines = new List<string> { "fast " + sw.ElapsedMilliseconds + " ms" };
                foreach (string p in f.Snapshot()) lines.Add("  " + p + "  |  " + Installer.Describe(p));
                Installer.DeepScan(f, 5, 25, delegate { return false; });
                lines.Add("deep " + sw.ElapsedMilliseconds + " ms, total " + f.Snapshot().Count);
                foreach (string p in f.Snapshot()) lines.Add("  " + p);
                try { File.WriteAllLines(Path.Combine(Path.GetTempPath(), "BetterThanCastle-Setup.log"), lines.ToArray()); } catch { }
                return 0;
            }
            Application.EnableVisualStyles();
            Application.SetCompatibleTextRenderingDefault(false);
            Application.Run(new SetupForm());
            return 0;
        }
    }

    internal static class Installer
    {
        private static readonly string[] LoaderFiles = { "winhttp.dll", "doorstop_config.ini", ".doorstop_version" };

        // BuildInfo.ModVersion is generated by scripts/build-setup.ps1 from Plugin.Version.
        internal static string ModVersion() { return BuildInfo.ModVersion; }

        // ---- game discovery: every source adds candidate folders; Add() validates and dedupes ----

        internal sealed class Found
        {
            private readonly List<string> _list = new List<string>();
            private readonly HashSet<string> _seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            internal event Action<string> Added;

            internal List<string> Snapshot() { lock (_list) return new List<string>(_list); }

            // Accepts a game folder or a path to the exe (also quoted or with arguments, as in registry values).
            internal void Add(string path)
            {
                try
                {
                    if (string.IsNullOrEmpty(path)) return;
                    path = path.Trim().Trim('"');
                    int exe = path.IndexOf(Program.GameExe, StringComparison.OrdinalIgnoreCase);
                    if (exe >= 0) path = path.Substring(0, exe);
                    path = path.Replace('/', '\\').TrimEnd('\\');
                    if (path.Length < 2 || !LooksLikeGame(path)) return;
                    path = Path.GetFullPath(path);
                    lock (_list)
                    {
                        if (!_seen.Add(path)) return;
                        _list.Add(path);
                    }
                    Action<string> h = Added;
                    if (h != null) h(path);
                }
                catch { }
            }
        }

        internal static bool IsGameDir(string dir)
        {
            return !string.IsNullOrEmpty(dir) && File.Exists(Path.Combine(dir, Program.GameExe));
        }

        private static bool LooksLikeGame(string dir)
        {
            return IsGameDir(dir) && Directory.Exists(Path.Combine(dir, "Castle Story_Data"));
        }

        // Fast sources (well under a second): installer folder, saved choice, running game, Steam, uninstall entries,
        // Windows "programs that were run" lists (MuiCache, Compatibility Assistant), shortcuts, common folders.
        internal static void FindFast(Found f)
        {
            string here = AppDomain.CurrentDomain.BaseDirectory.TrimEnd('\\');
            for (string d = here; !string.IsNullOrEmpty(d); d = Path.GetDirectoryName(d)) { f.Add(d); if (d.Length <= 3) break; }
            Try(delegate { foreach (string line in File.ReadAllLines(SavedPathFile())) f.Add(line); });
            Try(delegate
            {
                foreach (Process p in Process.GetProcessesByName("Castle Story"))
                {
                    try { f.Add(p.MainModule.FileName); } catch { }
                }
            });
            Try(delegate
            {
                foreach (string lib in SteamLibraries())
                {
                    f.Add(Path.Combine(lib, @"steamapps\common\Castle Story"));
                    string manifest = Path.Combine(lib, @"steamapps\appmanifest_" + Program.SteamAppId + ".acf");
                    if (!File.Exists(manifest)) continue;
                    Match m = Regex.Match(File.ReadAllText(manifest), "\"installdir\"\\s*\"([^\"]+)\"");
                    if (m.Success) f.Add(Path.Combine(lib, @"steamapps\common\" + m.Groups[1].Value));
                }
            });
            foreach (RegistryKey root in new[] { Registry.CurrentUser, Registry.LocalMachine })
            {
                foreach (string key in new[] { @"Software\Microsoft\Windows\CurrentVersion\Uninstall", @"Software\WOW6432Node\Microsoft\Windows\CurrentVersion\Uninstall" })
                {
                    RegistryKey r = root;
                    string k0 = key;
                    Try(delegate
                    {
                        using (RegistryKey u = r.OpenSubKey(k0))
                        {
                            if (u == null) return;
                            foreach (string sub in u.GetSubKeyNames())
                            {
                                using (RegistryKey s = u.OpenSubKey(sub))
                                {
                                    if (s == null) continue;
                                    string name = Convert.ToString(s.GetValue("DisplayName"));
                                    if (sub == "Steam App " + Program.SteamAppId || name.IndexOf("Castle Story", StringComparison.OrdinalIgnoreCase) >= 0)
                                    {
                                        f.Add(Convert.ToString(s.GetValue("InstallLocation")));
                                        f.Add(Convert.ToString(s.GetValue("DisplayIcon")));
                                    }
                                }
                            }
                        }
                    });
                }
            }
            foreach (string key in new[] { @"Software\Classes\Local Settings\Software\Microsoft\Windows\Shell\MuiCache",
                                           @"Software\Microsoft\Windows NT\CurrentVersion\AppCompatFlags\Compatibility Assistant\Store",
                                           @"Software\Microsoft\Windows NT\CurrentVersion\AppCompatFlags\Layers" })
            {
                string k0 = key;
                Try(delegate
                {
                    using (RegistryKey k = Registry.CurrentUser.OpenSubKey(k0))
                    {
                        if (k == null) return;
                        foreach (string v in k.GetValueNames())
                            if (v.IndexOf(Program.GameExe, StringComparison.OrdinalIgnoreCase) >= 0) f.Add(v);
                    }
                });
            }
            Try(delegate { ScanShortcuts(f); });
            Try(delegate
            {
                foreach (DriveInfo dr in DriveInfo.GetDrives())
                {
                    if (dr.DriveType != DriveType.Fixed || !dr.IsReady) continue;
                    string r = dr.RootDirectory.FullName;
                    foreach (string rel in new[] { @"SteamLibrary\steamapps\common\Castle Story", @"Steam\steamapps\common\Castle Story",
                                                   @"Program Files (x86)\Steam\steamapps\common\Castle Story", @"Program Files\Steam\steamapps\common\Castle Story",
                                                   @"Games\Castle Story", @"Games\Steam\steamapps\common\Castle Story", @"Castle Story" })
                        f.Add(Path.Combine(r, rel));
                }
            });
        }

        // Slow source: walks every fixed drive a few levels deep (folders only), stops after `seconds`.
        internal static void DeepScan(Found f, int maxDepth, int seconds, Func<bool> cancelled)
        {
            DateTime until = DateTime.UtcNow.AddSeconds(seconds);
            var skip = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "Windows", "$Recycle.Bin", "System Volume Information", "ProgramData", "Recovery",
                "AppData", "node_modules", ".git", "WinSxS", "Microsoft", "Windows Kits", "Microsoft SDKs", "dotnet", "Packages", "obj", "bin", "ref" };
            var q = new Queue<KeyValuePair<string, int>>();
            foreach (DriveInfo dr in DriveInfo.GetDrives())
            {
                try { if (dr.DriveType == DriveType.Fixed && dr.IsReady) q.Enqueue(new KeyValuePair<string, int>(dr.RootDirectory.FullName, 0)); } catch { }
            }
            while (q.Count > 0 && DateTime.UtcNow < until && !cancelled())
            {
                KeyValuePair<string, int> cur = q.Dequeue();
                string[] subs;
                try { subs = Directory.GetDirectories(cur.Key); } catch { continue; }
                foreach (string s in subs)
                {
                    string name = Path.GetFileName(s);
                    if (skip.Contains(name)) continue;
                    try { if ((new DirectoryInfo(s).Attributes & FileAttributes.ReparsePoint) != 0) continue; } catch { continue; }
                    if (File.Exists(Path.Combine(s, Program.GameExe))) f.Add(s);
                    if (cur.Value + 1 < maxDepth) q.Enqueue(new KeyValuePair<string, int>(s, cur.Value + 1));
                }
            }
        }

        // .lnk files on desktops and in Start menus that point at the game exe (resolved through WScript.Shell).
        private static void ScanShortcuts(Found f)
        {
            var dirs = new List<string>();
            foreach (Environment.SpecialFolder sf in new[] { Environment.SpecialFolder.DesktopDirectory, Environment.SpecialFolder.CommonDesktopDirectory,
                                                             Environment.SpecialFolder.StartMenu, Environment.SpecialFolder.CommonStartMenu })
            {
                try { string d = Environment.GetFolderPath(sf); if (!string.IsNullOrEmpty(d)) dirs.Add(d); } catch { }
            }
            Type t = Type.GetTypeFromProgID("WScript.Shell");
            if (t == null) return;
            object shell = Activator.CreateInstance(t);
            foreach (string d in dirs)
            {
                string[] links;
                try { links = Directory.GetFiles(d, "*.lnk", SearchOption.AllDirectories); } catch { continue; }
                foreach (string l in links)
                {
                    try
                    {
                        object sc = t.InvokeMember("CreateShortcut", BindingFlags.InvokeMethod, null, shell, new object[] { l });
                        string target = Convert.ToString(sc.GetType().InvokeMember("TargetPath", BindingFlags.GetProperty, null, sc, null));
                        if (target.EndsWith(Program.GameExe, StringComparison.OrdinalIgnoreCase)) f.Add(target);
                    }
                    catch { }
                }
            }
        }

        internal static string SavedPathFile()
        {
            return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), @"BetterThanCastle\setup-paths.txt");
        }

        internal static void RememberPath(string game)
        {
            try
            {
                string file = SavedPathFile();
                Directory.CreateDirectory(Path.GetDirectoryName(file));
                var lines = new List<string> { game };
                if (File.Exists(file))
                    foreach (string l in File.ReadAllLines(file))
                        if (!l.Equals(game, StringComparison.OrdinalIgnoreCase) && lines.Count < 10) lines.Add(l);
                File.WriteAllLines(file, lines.ToArray());
            }
            catch { }
        }

        // One-line state of a candidate folder for the UI.
        internal static string Describe(string game)
        {
            bool bep = File.Exists(Path.Combine(game, @"BepInEx\core\BepInEx.dll"));
            string dll = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle\BetterThanCastle.dll");
            string mod = Program.T("mod not installed", "мод не установлен");
            if (File.Exists(dll))
            {
                string v = "?";
                try { FileVersionInfo fi = FileVersionInfo.GetVersionInfo(dll); v = fi.FileMajorPart + "." + fi.FileMinorPart + "." + fi.FileBuildPart; } catch { }
                mod = Program.T("mod ", "мод ") + v + Program.T(" installed", " установлен");
            }
            return "BepInEx: " + (bep ? Program.T("yes", "есть") : Program.T("no", "нет")) + ",  " + mod;
        }

        private static void Try(Action a)
        {
            try { a(); } catch { }
        }

        private static List<string> SteamLibraries()
        {
            var libs = new List<string>();
            string steam = null;
            foreach (RegistryKey root in new[] { Registry.CurrentUser, Registry.LocalMachine })
            {
                foreach (string key in new[] { @"Software\Valve\Steam", @"Software\WOW6432Node\Valve\Steam" })
                {
                    try
                    {
                        using (RegistryKey k = root.OpenSubKey(key))
                        {
                            if (k == null) continue;
                            object v = k.GetValue("SteamPath") ?? k.GetValue("InstallPath");
                            if (v != null && steam == null) steam = v.ToString().Replace('/', '\\');
                        }
                    }
                    catch { }
                }
            }
            if (steam == null) steam = @"C:\Program Files (x86)\Steam";
            libs.Add(steam);
            try
            {
                string vdf = Path.Combine(steam, @"steamapps\libraryfolders.vdf");
                if (File.Exists(vdf))
                {
                    foreach (Match m in Regex.Matches(File.ReadAllText(vdf), "\"path\"\\s*\"([^\"]+)\""))
                    {
                        string p = m.Groups[1].Value.Replace(@"\\", @"\");
                        if (!libs.Contains(p)) libs.Add(p);
                    }
                }
            }
            catch { }
            return libs;
        }

        internal static bool IgnoreRunning;

        internal static bool GameRunning()
        {
            return !IgnoreRunning && Process.GetProcessesByName("Castle Story").Length > 0;
        }

        internal static string Install(string game, Action<string> log)
        {
            if (!IsGameDir(game)) throw new Exception(Program.T("\"" + Program.GameExe + "\" not found in this folder", "В этой папке нет \"" + Program.GameExe + "\""));
            if (GameRunning()) throw new Exception(Program.T("Close Castle Story first", "Сначала закройте Castle Story"));

            string core = Path.Combine(game, @"BepInEx\core\BepInEx.dll");
            bool hasBep = File.Exists(core) && File.Exists(Path.Combine(game, "winhttp.dll"));
            if (hasBep && OlderThan(core, new Version(5, 4, 23, 5)))
            {
                log(Program.T("Old BepInEx found, updating it", "Найден старый BepInEx, обновляю"));
                hasBep = false;
            }
            if (!hasBep)
            {
                log(Program.T("Installing BepInEx 5.4.23.5...", "Устанавливаю BepInEx 5.4.23.5..."));
                using (Stream s = Res("BepInEx.zip"))
                using (var zip = new ZipArchive(s, ZipArchiveMode.Read))
                {
                    foreach (ZipArchiveEntry e in zip.Entries)
                    {
                        if (string.IsNullOrEmpty(e.Name)) continue;
                        if (e.FullName == "changelog.txt") continue;
                        string dst = Path.GetFullPath(Path.Combine(game, e.FullName.Replace('/', '\\')));
                        if (!dst.StartsWith(Path.GetFullPath(game), StringComparison.OrdinalIgnoreCase)) continue;
                        Directory.CreateDirectory(Path.GetDirectoryName(dst));
                        using (Stream es = e.Open())
                        using (FileStream fs = File.Create(dst)) es.CopyTo(fs);
                    }
                }
            }
            else log(Program.T("BepInEx is already installed", "BepInEx уже установлен"));

            FixEntrypoint(game, log);

            string plug = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle");
            Directory.CreateDirectory(plug);
            string dll = Path.Combine(plug, "BetterThanCastle.dll");
            using (Stream s = Res("BetterThanCastle.dll"))
            {
                byte[] b = ReadAll(s);
                File.WriteAllBytes(dll, b);
            }
            foreach (string junk in new[] { dll + ".old", dll + ".new", Path.Combine(plug, "BetterThanCastle.pdb") })
            {
                try { if (File.Exists(junk)) File.Delete(junk); } catch { }
            }
            // A stray copy in plugins/ root would load the mod twice.
            try
            {
                string stray = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle.dll");
                if (File.Exists(stray)) { File.Delete(stray); log(Program.T("Removed a second copy from BepInEx\\plugins", "Удалена вторая копия из BepInEx\\plugins")); }
            }
            catch { }
            log(Program.T("Mod installed: ", "Мод установлен: ") + dll);
            RememberPath(Path.GetFullPath(game));
            return Program.T("Done. Start Castle Story through Steam; the mod menu opens with PageDown.",
                             "Готово. Запускайте Castle Story через Steam, меню мода открывается клавишей PageDown.");
        }

        internal static string Uninstall(string game, bool removeBepInEx, Action<string> log)
        {
            if (!IsGameDir(game)) throw new Exception(Program.T("\"" + Program.GameExe + "\" not found in this folder", "В этой папке нет \"" + Program.GameExe + "\""));
            if (GameRunning()) throw new Exception(Program.T("Close Castle Story first", "Сначала закройте Castle Story"));
            string plug = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle");
            if (Directory.Exists(plug)) { Directory.Delete(plug, true); log(Program.T("Mod removed", "Мод удалён")); }
            else log(Program.T("Mod was not installed", "Мод не был установлен"));
            if (removeBepInEx)
            {
                // Only the loader and BepInEx/core: other mods' plugins and configs stay.
                foreach (string f in LoaderFiles)
                {
                    string p = Path.Combine(game, f);
                    if (File.Exists(p)) File.Delete(p);
                }
                string core = Path.Combine(game, @"BepInEx\core");
                if (Directory.Exists(core)) Directory.Delete(core, true);
                log(Program.T("BepInEx loader removed (BepInEx\\plugins and config kept)", "Загрузчик BepInEx удалён (BepInEx\\plugins и config оставлены)"));
            }
            return Program.T("Done. Your settings and replays in <game>\\BetterThanCastle are kept.",
                             "Готово. Ваши настройки и реплеи в <игра>\\BetterThanCastle сохранены.");
        }

        // BepInEx on this Unity version only starts with Preloader.Entrypoint Assembly = UnityEngine.dll (stock default).
        private static void FixEntrypoint(string game, Action<string> log)
        {
            string cfg = Path.Combine(game, @"BepInEx\config\BepInEx.cfg");
            if (!File.Exists(cfg)) return;
            string text = File.ReadAllText(cfg);
            var rx = new Regex(@"(\[Preloader\.Entrypoint\][^\[]*?\r?\nAssembly\s*=\s*)([^\r\n]*)");
            Match m = rx.Match(text);
            if (m.Success && m.Groups[2].Value.Trim() != "UnityEngine.dll")
            {
                File.WriteAllText(cfg, rx.Replace(text, "${1}UnityEngine.dll", 1));
                log(Program.T("BepInEx.cfg: entrypoint set to UnityEngine.dll", "BepInEx.cfg: точка входа исправлена на UnityEngine.dll"));
            }
        }

        private static bool OlderThan(string dll, Version v)
        {
            try
            {
                FileVersionInfo fi = FileVersionInfo.GetVersionInfo(dll);
                return new Version(fi.FileMajorPart, fi.FileMinorPart, fi.FileBuildPart, fi.FilePrivatePart) < v;
            }
            catch { return false; }
        }

        private static Stream Res(string name)
        {
            Stream s = Assembly.GetExecutingAssembly().GetManifestResourceStream(name);
            if (s == null) throw new Exception("embedded resource missing: " + name);
            return s;
        }

        private static byte[] ReadAll(Stream s)
        {
            using (var ms = new MemoryStream())
            {
                s.CopyTo(ms);
                return ms.ToArray();
            }
        }
    }

