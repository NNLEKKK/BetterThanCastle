        private void AddCandidate(string p)
        {
            foreach (object o in _path.Items) if (string.Equals((string)o, p, StringComparison.OrdinalIgnoreCase)) return;
            _path.Items.Add(p);
            if (_path.Items.Count == 1 && _path.Text.Trim().Length == 0) _path.SelectedIndex = 0;
            if (_path.Items.Count == 2) Log(Program.T("Several copies of the game were found: choose one in the list.", "Найдено несколько копий игры: выберите нужную в списке."));
            UpdateScanLabel(null);
        }

        private void StartDeepScan()
        {
            UpdateScanLabel(Program.T("searching the disks...", "ищу на дисках..."));
            var th = new System.Threading.Thread(delegate()
            {
                try { Installer.DeepScan(_found, 5, 25, delegate { return _closing; }); } catch { }
                if (_closing) return;
                try
                {
                    BeginInvoke(new Action(delegate
                    {
                        UpdateScanLabel(Program.T("search finished", "поиск завершён"));
                        if (_path.Items.Count == 0)
                            Log(Program.T("Castle Story was not found: press Browse and pick the folder with \"Castle Story.exe\".",
                                          "Castle Story не найдена: нажмите \"Обзор\" и выберите папку с \"Castle Story.exe\"."));
                    }));
                }
                catch { }
            });
            th.IsBackground = true;
            th.Start();
        }

        private string _scanText = "";
        private void UpdateScanLabel(string s)
        {
            if (s != null) _scanText = s;
            _scan.Text = Program.T("Found: ", "Найдено: ") + _path.Items.Count + (_scanText.Length > 0 ? "  (" + _scanText + ")" : "");
        }

        private void UpdateState()
        {
            string g = _path.Text.Trim().TrimEnd('\\');
            if (g.Length == 0) { _state.Text = ""; return; }
            if (!Installer.IsGameDir(g)) { _state.ForeColor = Color.Firebrick; _state.Text = Program.T("No \"Castle Story.exe\" in this folder", "В этой папке нет \"Castle Story.exe\""); return; }
            _state.ForeColor = Color.DarkGreen;
            _state.Text = Installer.Describe(g);
        }

        private void Browse()
        {
            using (var d = new FolderBrowserDialog())
            {
                d.Description = Program.T("Folder with \"Castle Story.exe\"", "Папка с \"Castle Story.exe\"");
                if (Directory.Exists(_path.Text)) d.SelectedPath = _path.Text;
                if (d.ShowDialog(this) == DialogResult.OK) _path.Text = d.SelectedPath;
            }
        }

        private void Log(string s)
        {
            _log.AppendText(s + Environment.NewLine);
        }

        private void Run(bool install)
        {
            try
            {
                Cursor = Cursors.WaitCursor;
                string game = _path.Text.Trim().TrimEnd('\\');
                string result = install ? Installer.Install(game, Log) : Installer.Uninstall(game, _withBep.Checked, Log);
                Log(result);
                MessageBox.Show(this, result, "Better Than Castle", MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (UnauthorizedAccessException)
            {
                string m = Program.T("No write access to the game folder. Run the installer as administrator.", "Нет доступа к папке игры. Запустите установщик от имени администратора.");
                Log(m);
                MessageBox.Show(this, m, "Better Than Castle", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (Exception e)
            {
                Log(Program.T("Error: ", "Ошибка: ") + e.Message);
                MessageBox.Show(this, e.Message, "Better Than Castle", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            finally { Cursor = Cursors.Default; UpdateState(); }
        }
    }
