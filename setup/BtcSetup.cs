// Built by scripts/build-setup.ps1 with the .NET Framework 4 csc (C# 5: no interpolation, no ?. operators).
// Never touches game files: it only adds the BepInEx loader (winhttp.dll, doorstop_config.ini, .doorstop_version,
// BepInEx/core) next to the game exe and the mod into BepInEx/plugins/BetterThanCastle.
