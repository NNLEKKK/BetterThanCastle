// Better Than Castle installer: one exe with embedded BepInEx (official win_x64 zip) and BetterThanCastle.dll.
// Built by scripts/build-setup.ps1 with the .NET Framework 4 csc (C# 5: no interpolation, no ?. operators).
// Never touches game files: it only adds the BepInEx loader (winhttp.dll, doorstop_config.ini, .doorstop_version,
// BepInEx/core) next to the game exe and the mod into BepInEx/plugins/BetterThanCastle.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Drawing;
using System.Globalization;
using System.IO;
using System.IO.Compression;
using System.Reflection;
using System.Text.RegularExpressions;
using System.Windows.Forms;
using Microsoft.Win32;

[assembly: AssemblyTitle("Better Than Castle Setup")]
[assembly: AssemblyProduct("Better Than Castle")]

namespace BtcSetup
{
    internal static class Program
    {
        internal const string GameExe = "Castle Story.exe";
        internal const string SteamAppId = "227860";
        internal static readonly bool Ru = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName == "ru";

        internal static string T(string en, string ru) { return Ru ? ru : en; }

        [STAThread]
        private static int Main(string[] args)
        {
            // Silent mode for scripts/tests: BetterThanCastle-Setup.exe /silent "<game dir>" [/ignore-running]
            // (winexe has no console: the log goes to %TEMP%\BetterThanCastle-Setup.log).
            if (args.Length >= 2 && args[0].Equals("/silent", StringComparison.OrdinalIgnoreCase))
            {
                Installer.IgnoreRunning = args.Length >= 3 && args[2].Equals("/ignore-running", StringComparison.OrdinalIgnoreCase);
                string logPath = Path.Combine(Path.GetTempPath(), "BetterThanCastle-Setup.log");
                var lines = new List<string>();
                int code = 0;
                try { lines.Add(Installer.Install(args[1], delegate(string s) { lines.Add(s); })); }
                catch (Exception e) { lines.Add("ERROR: " + e.Message); code = 1; }
                try { File.WriteAllLines(logPath, lines.ToArray()); } catch { }
                return code;
            }
            Application.EnableVisualStyles();
            Application.SetCompatibleTextRenderingDefault(false);
            Application.Run(new SetupForm());
            return 0;
        }
    }

    internal static class Installer
    {
        private static readonly string[] LoaderFiles = { "winhttp.dll", "doorstop_config.ini", ".doorstop_version" };

        // BuildInfo.ModVersion is generated by scripts/build-setup.ps1 from Plugin.Version.
        internal static string ModVersion() { return BuildInfo.ModVersion; }

        internal static string FindGame()
        {
            string here = AppDomain.CurrentDomain.BaseDirectory;
            if (IsGameDir(here)) return here.TrimEnd('\\');
            foreach (string lib in SteamLibraries())
            {
                string dir = Path.Combine(lib, @"steamapps\common\Castle Story");
                if (IsGameDir(dir)) return dir;
                string manifest = Path.Combine(lib, @"steamapps\appmanifest_" + Program.SteamAppId + ".acf");
                if (File.Exists(manifest))
                {
                    Match m = Regex.Match(File.ReadAllText(manifest), "\"installdir\"\\s*\"([^\"]+)\"");
                    if (m.Success)
                    {
                        dir = Path.Combine(lib, @"steamapps\common\" + m.Groups[1].Value);
                        if (IsGameDir(dir)) return dir;
                    }
                }
            }
            return null;
        }

        internal static bool IsGameDir(string dir)
        {
            return !string.IsNullOrEmpty(dir) && File.Exists(Path.Combine(dir, Program.GameExe));
        }

        private static List<string> SteamLibraries()
        {
            var libs = new List<string>();
            string steam = null;
            foreach (RegistryKey root in new[] { Registry.CurrentUser, Registry.LocalMachine })
            {
                foreach (string key in new[] { @"Software\Valve\Steam", @"Software\WOW6432Node\Valve\Steam" })
                {
                    try
                    {
                        using (RegistryKey k = root.OpenSubKey(key))
                        {
                            if (k == null) continue;
                            object v = k.GetValue("SteamPath") ?? k.GetValue("InstallPath");
                            if (v != null && steam == null) steam = v.ToString().Replace('/', '\\');
                        }
                    }
                    catch { }
                }
            }
            if (steam == null) steam = @"C:\Program Files (x86)\Steam";
            libs.Add(steam);
            try
            {
                string vdf = Path.Combine(steam, @"steamapps\libraryfolders.vdf");
                if (File.Exists(vdf))
                {
                    foreach (Match m in Regex.Matches(File.ReadAllText(vdf), "\"path\"\\s*\"([^\"]+)\""))
                    {
                        string p = m.Groups[1].Value.Replace(@"\\", @"\");
                        if (!libs.Contains(p)) libs.Add(p);
                    }
                }
            }
            catch { }
            return libs;
        }

        internal static bool IgnoreRunning;

        internal static bool GameRunning()
        {
            return !IgnoreRunning && Process.GetProcessesByName("Castle Story").Length > 0;
        }

        internal static string Install(string game, Action<string> log)
        {
            if (!IsGameDir(game)) throw new Exception(Program.T("\"" + Program.GameExe + "\" not found in this folder", "В этой папке нет \"" + Program.GameExe + "\""));
            if (GameRunning()) throw new Exception(Program.T("Close Castle Story first", "Сначала закройте Castle Story"));

            string core = Path.Combine(game, @"BepInEx\core\BepInEx.dll");
            bool hasBep = File.Exists(core) && File.Exists(Path.Combine(game, "winhttp.dll"));
            if (hasBep && OlderThan(core, new Version(5, 4, 23, 5)))
            {
                log(Program.T("Old BepInEx found, updating it", "Найден старый BepInEx, обновляю"));
                hasBep = false;
            }
            if (!hasBep)
            {
                log(Program.T("Installing BepInEx 5.4.23.5...", "Устанавливаю BepInEx 5.4.23.5..."));
                using (Stream s = Res("BepInEx.zip"))
                using (var zip = new ZipArchive(s, ZipArchiveMode.Read))
                {
                    foreach (ZipArchiveEntry e in zip.Entries)
                    {
                        if (string.IsNullOrEmpty(e.Name)) continue;
                        if (e.FullName == "changelog.txt") continue;
                        string dst = Path.GetFullPath(Path.Combine(game, e.FullName.Replace('/', '\\')));
                        if (!dst.StartsWith(Path.GetFullPath(game), StringComparison.OrdinalIgnoreCase)) continue;
                        Directory.CreateDirectory(Path.GetDirectoryName(dst));
                        using (Stream es = e.Open())
                        using (FileStream fs = File.Create(dst)) es.CopyTo(fs);
                    }
                }
            }
            else log(Program.T("BepInEx is already installed", "BepInEx уже установлен"));

            FixEntrypoint(game, log);

            string plug = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle");
            Directory.CreateDirectory(plug);
            string dll = Path.Combine(plug, "BetterThanCastle.dll");
            using (Stream s = Res("BetterThanCastle.dll"))
            {
                byte[] b = ReadAll(s);
                File.WriteAllBytes(dll, b);
            }
            foreach (string junk in new[] { dll + ".old", dll + ".new", Path.Combine(plug, "BetterThanCastle.pdb") })
            {
                try { if (File.Exists(junk)) File.Delete(junk); } catch { }
            }
            // A stray copy in plugins/ root would load the mod twice.
            try
            {
                string stray = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle.dll");
                if (File.Exists(stray)) { File.Delete(stray); log(Program.T("Removed a second copy from BepInEx\\plugins", "Удалена вторая копия из BepInEx\\plugins")); }
            }
            catch { }
            log(Program.T("Mod installed: ", "Мод установлен: ") + dll);
            return Program.T("Done. Start Castle Story through Steam; the mod menu opens with PageDown.",
                             "Готово. Запускайте Castle Story через Steam, меню мода открывается клавишей PageDown.");
        }

        internal static string Uninstall(string game, bool removeBepInEx, Action<string> log)
        {
            if (!IsGameDir(game)) throw new Exception(Program.T("\"" + Program.GameExe + "\" not found in this folder", "В этой папке нет \"" + Program.GameExe + "\""));
            if (GameRunning()) throw new Exception(Program.T("Close Castle Story first", "Сначала закройте Castle Story"));
            string plug = Path.Combine(game, @"BepInEx\plugins\BetterThanCastle");
            if (Directory.Exists(plug)) { Directory.Delete(plug, true); log(Program.T("Mod removed", "Мод удалён")); }
            else log(Program.T("Mod was not installed", "Мод не был установлен"));
            if (removeBepInEx)
            {
                // Only the loader and BepInEx/core: other mods' plugins and configs stay.
                foreach (string f in LoaderFiles)
                {
                    string p = Path.Combine(game, f);
                    if (File.Exists(p)) File.Delete(p);
                }
                string core = Path.Combine(game, @"BepInEx\core");
                if (Directory.Exists(core)) Directory.Delete(core, true);
                log(Program.T("BepInEx loader removed (BepInEx\\plugins and config kept)", "Загрузчик BepInEx удалён (BepInEx\\plugins и config оставлены)"));
            }
            return Program.T("Done. Your settings and replays in <game>\\BetterThanCastle are kept.",
                             "Готово. Ваши настройки и реплеи в <игра>\\BetterThanCastle сохранены.");
        }

        // BepInEx on this Unity version only starts with Preloader.Entrypoint Assembly = UnityEngine.dll (stock default).
        private static void FixEntrypoint(string game, Action<string> log)
        {
            string cfg = Path.Combine(game, @"BepInEx\config\BepInEx.cfg");
            if (!File.Exists(cfg)) return;
            string text = File.ReadAllText(cfg);
            var rx = new Regex(@"(\[Preloader\.Entrypoint\][^\[]*?\r?\nAssembly\s*=\s*)([^\r\n]*)");
            Match m = rx.Match(text);
            if (m.Success && m.Groups[2].Value.Trim() != "UnityEngine.dll")
            {
                File.WriteAllText(cfg, rx.Replace(text, "${1}UnityEngine.dll", 1));
                log(Program.T("BepInEx.cfg: entrypoint set to UnityEngine.dll", "BepInEx.cfg: точка входа исправлена на UnityEngine.dll"));
            }
        }

        private static bool OlderThan(string dll, Version v)
        {
            try
            {
                FileVersionInfo fi = FileVersionInfo.GetVersionInfo(dll);
                return new Version(fi.FileMajorPart, fi.FileMinorPart, fi.FileBuildPart, fi.FilePrivatePart) < v;
            }
            catch { return false; }
        }

        private static Stream Res(string name)
        {
            Stream s = Assembly.GetExecutingAssembly().GetManifestResourceStream(name);
            if (s == null) throw new Exception("embedded resource missing: " + name);
            return s;
        }

        private static byte[] ReadAll(Stream s)
        {
            using (var ms = new MemoryStream())
            {
                s.CopyTo(ms);
                return ms.ToArray();
            }
        }
    }

    internal sealed class SetupForm : Form
    {
        private readonly TextBox _path = new TextBox();
        private readonly TextBox _log = new TextBox();
        private readonly CheckBox _withBep = new CheckBox();

        internal SetupForm()
        {
            string ver = Installer.ModVersion();
            Text = "Better Than Castle " + ver + " - " + Program.T("Setup", "Установка");
            ClientSize = new Size(620, 330);
            FormBorderStyle = FormBorderStyle.FixedDialog;
            MaximizeBox = false;
            StartPosition = FormStartPosition.CenterScreen;
            Font = new Font("Segoe UI", 9.5f);
            try { Icon = Icon.ExtractAssociatedIcon(Application.ExecutablePath); } catch { }

            var title = new Label { Text = "Better Than Castle " + ver, Font = new Font("Segoe UI", 15f, FontStyle.Bold), Location = new Point(14, 10), AutoSize = true };
            var hint = new Label
            {
                Text = Program.T("Installs BepInEx 5.4.23.5 (if missing) and the mod. Game files are not changed.",
                                 "Ставит BepInEx 5.4.23.5 (если его нет) и мод. Файлы игры не изменяются."),
                Location = new Point(16, 46), AutoSize = true
            };
            var lbl = new Label { Text = Program.T("Castle Story folder:", "Папка Castle Story:"), Location = new Point(16, 78), AutoSize = true };
            _path.Location = new Point(16, 100);
            _path.Width = 500;
            _path.Text = Installer.FindGame() ?? "";
            var browse = new Button { Text = Program.T("Browse...", "Обзор..."), Location = new Point(524, 98), Width = 80 };
            browse.Click += delegate { Browse(); };

            var install = new Button { Text = Program.T("Install / update", "Установить / обновить"), Location = new Point(16, 136), Size = new Size(190, 34), Font = new Font("Segoe UI", 10f, FontStyle.Bold) };
            install.Click += delegate { Run(true); };
            var uninstall = new Button { Text = Program.T("Uninstall mod", "Удалить мод"), Location = new Point(216, 136), Size = new Size(130, 34) };
            uninstall.Click += delegate { Run(false); };
            _withBep.Text = Program.T("also remove BepInEx", "удалить и BepInEx");
            _withBep.Location = new Point(356, 144);
            _withBep.AutoSize = true;

            _log.Location = new Point(16, 182);
            _log.Size = new Size(588, 134);
            _log.Multiline = true;
            _log.ReadOnly = true;
            _log.ScrollBars = ScrollBars.Vertical;
            if (_path.Text.Length == 0) Log(Program.T("Castle Story was not found automatically: press Browse and pick the folder with \"Castle Story.exe\".",
                                                      "Castle Story не найдена автоматически: нажмите \"Обзор\" и выберите папку с \"Castle Story.exe\"."));
            else Log(Program.T("Game found. Press Install.", "Игра найдена. Нажмите \"Установить\"."));

            Controls.AddRange(new Control[] { title, hint, lbl, _path, browse, install, uninstall, _withBep, _log });
            AcceptButton = install;
        }

        private void Browse()
        {
            using (var d = new FolderBrowserDialog())
            {
                d.Description = Program.T("Folder with \"Castle Story.exe\"", "Папка с \"Castle Story.exe\"");
                if (Directory.Exists(_path.Text)) d.SelectedPath = _path.Text;
                if (d.ShowDialog(this) == DialogResult.OK) _path.Text = d.SelectedPath;
            }
        }

        private void Log(string s)
        {
            _log.AppendText(s + Environment.NewLine);
        }

        private void Run(bool install)
        {
            try
            {
                Cursor = Cursors.WaitCursor;
                string game = _path.Text.Trim().TrimEnd('\\');
                string result = install ? Installer.Install(game, Log) : Installer.Uninstall(game, _withBep.Checked, Log);
                Log(result);
                MessageBox.Show(this, result, "Better Than Castle", MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (UnauthorizedAccessException)
            {
                string m = Program.T("No write access to the game folder. Run the installer as administrator.", "Нет доступа к папке игры. Запустите установщик от имени администратора.");
                Log(m);
                MessageBox.Show(this, m, "Better Than Castle", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            catch (Exception e)
            {
                Log(Program.T("Error: ", "Ошибка: ") + e.Message);
                MessageBox.Show(this, e.Message, "Better Than Castle", MessageBoxButtons.OK, MessageBoxIcon.Warning);
            }
            finally { Cursor = Cursors.Default; }
        }
    }
